-- The current choice takes effect immediately, without waiting for /reload.
-- English is the default on a new installation. A saved
-- choice takes priority and is never overwritten.
local runtimeLanguage
local DEFAULT_LANGUAGE = "en"

-- Native names, never translated, in dropdown order.
AL.UI_LANGUAGES = {
	{ code = "en", name = "English" },
	{ code = "fr", name = "Français" },
	{ code = "pt", name = "Português" },
	{ code = "es", name = "Español" },
	{ code = "de", name = "Deutsch" },
	{ code = "zh", name = "简体中文" },
}

local function ValidLanguage(language)
	return type(language) == "string" and T[language] ~= nil
end

function AL.GetUILanguage()
	if ValidLanguage(runtimeLanguage) then return runtimeLanguage end

	local language = ActionLiteLanguage
	if not ValidLanguage(language) then
		language = ActionLiteDB and ActionLiteDB.uiLanguage
	end
	if not ValidLanguage(language) and ActionLiteDB and ActionLiteDB.profiles then
		local uiProfile = ActionLiteDB.profiles.__ACTIONLITE_UI
		language = uiProfile and uiProfile.language
	end
	if not ValidLanguage(language) then language = DEFAULT_LANGUAGE end
	runtimeLanguage = language
	return language
end

function AL.SetUILanguage(language)
	if not ValidLanguage(language) then language = DEFAULT_LANGUAGE end
	runtimeLanguage = language
	ActionLiteLanguage = language
	ActionLiteDB = ActionLiteDB or {}
	ActionLiteDB.uiLanguage = language
	-- Redundant copy in the profiles table, which Forever is already known
	-- to preserve correctly (thresholds, spells and class options).
	ActionLiteDB.profiles = ActionLiteDB.profiles or {}
	ActionLiteDB.profiles.__ACTIONLITE_UI =
		ActionLiteDB.profiles.__ACTIONLITE_UI or {}
	ActionLiteDB.profiles.__ACTIONLITE_UI.language = language
	return language
end

function AL.L(key, ...)
	local language = AL.GetUILanguage()
	local value = (T[language] and T[language][key]) or T.en[key] or tostring(key)
	if select("#", ...) > 0 then
		local ok, formatted = pcall(string.format, value, ...)
		if ok then return formatted end
	end
	return value
end

function AL.UIClassName(token)
	local key = CLASS_KEYS[token]
	return key and AL.L(key) or tostring(token or "")
end

